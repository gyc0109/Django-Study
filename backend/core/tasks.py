"""
core/tasks.py —— Celery 异步任务定义

# ==========================================================================
# 一、Celery 是什么？为什么要它？
# ==========================================================================
# 有些活儿很慢：发 1000 封邮件、生成 Excel 报表、调用第三方 API、处理图片……
# 如果都写在接口里「同步执行」，用户点击按钮后浏览器要转圈 30 秒，
# 稍微久一点 Nginx 就超时了（默认 60 秒），体验极差。
#
# Celery 的思路：把慢活儿「扔出去」，接口先返回，让另一个进程慢慢干。
#
# ==========================================================================
# 二、三个角色，缺一不可
# ==========================================================================
#  ┌──────────────┐   ①delay()   ┌──────────────┐   ②取任务   ┌──────────────┐
#  │ Django 进程   │ ───────────► │  Redis 队列   │ ◄────────── │ Celery worker │
#  │ （生产者）    │              │ （broker）    │             │ （消费者）    │
#  └──────┬───────┘              └──────┬───────┘             └──────┬───────┘
#         │                             │                            │
#         │ ④查结果 AsyncResult          │ ③写结果（result backend）   │
#         ▼                             ▼                            │
#      前端/浏览器 ◄──────────────────────┴────────────────────────────┘
#
#   broker（中间人）   = Redis 0 号库（见 settings.CELERY_BROKER_URL）
#   result backend     = 同一个 Redis 0 号库（本项目图省事复用了）
#   worker             = 需要单独另起一个进程，命令在项目根目录：
#                            celery -A config worker -l info
#
# ★ 最经典的踩坑：只跑了 runserver，没跑 worker。
#   这时 .delay() 不报错、接口也返回 202，但任务永远 PENDING ——
#   因为根本没人从队列里取活儿。
#
# ==========================================================================
# 三、两种调用方式（务必分清，这是 Celery 的入门坎）
# ==========================================================================
#   add(1, 2)         -> 普通函数调用，当场在当前进程算完，阻塞等待（同步）
#   add.delay(1, 2)   -> 只把任务投递到队列，立刻返回 AsyncResult（异步）
#
#   add(1, 2) 能跑通只能证明「函数没写错」；
#   要验证 Celery 整条链路是否通畅，必须用 .delay() + 启动 worker。
#
# ==========================================================================
# 四、为什么用 @shared_task 而不是 @app.task？
# ==========================================================================
#   @app.task     -> 必须 import 具体的 app 实例，容易造成循环导入；
#   @shared_task  -> 不绑定具体 app，Celery 启动时自动收集所有被装饰的函数，
#                    对「多 app 项目」（本项目有 core，未来还会有别的 app）更友好。
#   官方推荐：只要不是特殊场景，一律用 @shared_task。
# ==========================================================================
"""

# time 用于模拟耗时操作（time.sleep）
import time

# shared_task 是 Celery 提供的装饰器，把普通函数变成「可投递的任务」
from celery import shared_task


@shared_task
def add(a, b):
    """最简单的异步任务：算两个整数之和。

    【它存在的意义】
    不是真的为了做加法，而是「最小可验证单元」：
    如果这个任务能跑通，说明 broker / worker / backend 整条链都没问题。

    【参数】
    a, b : int —— 由调用方（.delay(a, b)）传进来。
           ★ Celery 会把参数序列化成 JSON 存进 Redis，
             所以参数必须是「可 JSON 序列化」的类型：
             能传 int / str / list / dict / None，
             不能传 datetime、Decimal、模型对象（需要先转成字符串/字典）。

    【返回值】
    a + b —— 这个值会被 worker 写回 result backend（Redis），
             前端通过 GET /api/tasks/{task_id}/ 就能读到。
    """
    return a + b


@shared_task
def slow_task(seconds=3):
    """模拟一个耗时任务（比如生成报表、批量发邮件）。

    【它存在的意义】
    用来亲身感受「异步」和「同步」的差别：
      - 同步写法：前端请求会卡住 N 秒，页面转圈，超时还会报错；
      - 异步写法：接口 20ms 就返回 task_id，秒开，任务在后台慢慢跑。

    【参数】
    seconds : int —— 要睡多少秒，默认 3。
              ★ 默认值只是「不传时的兜底」，实际调用时 .delay(5) 会覆盖它。

    ★ 缺点提醒：time.sleep 会占住一个 worker 进程。
      如果你的 worker 只开了 1 个并发（默认跟 CPU 核数有关，
      可用 celery ... --concurrency=4 调整），
      同时提交 5 个慢任务，后 4 个就只能排队等。
    """
    # 睡指定的秒数，模拟真实业务里的耗时操作
    time.sleep(seconds)

    # 返回值同样会写进 Redis 的 result backend，
    # 前端轮询到 SUCCESS 时就能看到这句话。
    return f"已完成 {seconds} 秒的耗时任务"
