# ★ Python 3.3+ 有「命名空间包」，理论上可以不要这个文件，
#   但 Django 的很多机制（app 发现、迁移扫描）都依赖它，
#   所以永远别删。startapp 也会自动帮你生成。
#
# ==========================================================================
# 这个文件为什么是空的？
# ==========================================================================
# 因为 core 这个 app 不需要在「包被导入时」做任何事。
# 它留空的另一个好处是：导入 core 不会触发任何副作用，
# 启动更快，也不会造成循环导入。
#
# ★ 对比 config/__init__.py 为什么写满了代码？
#   因为那里要注册 PyMySQL 并暴露 celery_app，
#   属于「必须尽早执行的启动动作」，所以放在包的入口。
#   两者职责不同：app 包的 __init__ 一般留空，配置包的 __init__ 可以干活。
# ==========================================================================
