/**
 * ============================================================================
 * vite.config.js —— Vite 的配置文件（开发服务器 + 打包行为）
 * ============================================================================
 *
 * 【Vite 是什么？】
 * 一个前端构建工具，干两件事：
 *   1. 开发时：启动本地服务器（默认 5173），按需编译源码、热更新（HMR），
 *      浏览器里改了代码，页面立即变化，不用手动刷新；
 *   2. 上线前：执行 npm run build，把所有 .vue / .js / .css 打包压缩成
 *      浏览器能直接用的静态文件（输出到 dist/ 目录）。
 *
 * 【前端项目为什么需要「服务器」？】
 * 因为双击打开 index.html（file:// 协议）会出问题：
 *   - 浏览器出于安全限制，file:// 下不能发跨域请求；
 *   - 不能写 /src/main.js 这种绝对路径；
 *   - .vue 文件浏览器也不认识。
 * 所以必须有一个本地 HTTP 服务器来「托管 + 编译」。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// import { defineConfig } from 'vite'
// ---------------------------------------------------------------------------
// 它就是个「类型提示辅助函数」，直接把配置对象 export default 也能跑，
// 但套一层 defineConfig 后，VS Code 里写配置会有自动补全和错误提示。
//
// ★ 注意：这是「具名导入」，必须带花括号。
import { defineConfig } from 'vite'

// ---------------------------------------------------------------------------
// import vue from '@vitejs/plugin-vue2'
// ---------------------------------------------------------------------------
// 让 Vite 能编译 .vue 单文件组件（SFC）。
//
// ★★★ 为什么是 plugin-vue2 而不是 plugin-vue？★★★
//   @vitejs/plugin-vue     -> 只支持 Vue 3
//   @vitejs/plugin-vue2    -> 支持 Vue 2.7
//   本项目是 Vue 2.7.16，装错插件会报：
//     [vite] Internal server error: ... Unexpected token
//   或者编译出来的东西根本跑不起来。
import vue from '@vitejs/plugin-vue2'

export default defineConfig({
  // -------------------------------------------------------------------------
  // plugins：插件列表
  // -------------------------------------------------------------------------
  // 有了 vue() 这个插件，import App from './App.vue' 才能工作：
  // 插件会把 .vue 文件里的 <template>/<script>/<style> 拆开，
  // template 编译成 render 函数，script 原样保留，style 注入到页面。
  //
  // ★ 顺序一般无所谓，但如果多个插件都要处理同一类文件，
  //   数组靠前的先执行（Vite 的插件是有顺序语义的）。
  plugins: [vue()],

  // -------------------------------------------------------------------------
  // server：开发服务器配置（只在 npm run dev 时生效）
  // -------------------------------------------------------------------------
  server: {
    // ---- 端口 ----
    // 本项目用 5173（Vite 的默认端口）。
    //
    // ★ 如果 5173 被占用（比如同时开着 practice 项目），
    //   Vite 默认会自动换成 5174 并在终端提示：
    //     Port 5173 is in use, trying another one...
    //   这时浏览器要访问新端口！但更麻烦的是：
    //   如果 Django 配了 CORS 白名单，新端口不在白名单里就会跨域失败。
    //
    // ★ 想让端口冲突时直接报错而不是自动换端口，加：
    //     strictPort: true
    port: 5173,

    // ★ 想用局域网其他设备（手机）访问，加这一行：
    //   host: '0.0.0.0'
    //   然后手机访问 http://你电脑的IP:5173

    // -----------------------------------------------------------------------
    // proxy：开发环境代理（解决跨域的核心配置）
    // -----------------------------------------------------------------------
    // 【为什么要代理？】
    //   前端跑在 http://localhost:5173
    //   后端跑在 http://127.0.0.1:8000
    //   端口不同 = 不同源 = 跨域。浏览器会拦截响应
    //   （除非后端配了 CORS 头）。
    //
    // 【代理怎么绕过跨域？】
    //   ★ 关键点：跨域是「浏览器」的限制，不是服务器的限制。
    //   让前端请求发给自己（5173），由 Vite（Node 进程，不是浏览器）转发给后端，
    //   浏览器全程只看到一个同源请求，自然不触发跨域检查。
    //
    //   请求链路图：
    //     浏览器 ──GET /api/notes/──► Vite:5173 ──转发──► Django:8000/api/notes/
    //        ▲                                              │
    //        └──────────────── 响应 ─────────────────────────┘
    //
    //   ★ 注意：这只在「开发环境」有效。上线后前端是静态文件，
    //     一般由 Nginx 做同样的反向代理（proxy_pass），
    //     或者干脆前后端同域部署。
    proxy: {
      // 键 = 需要代理的路径前缀。
      // 所有以 /api 开头的请求都会被拦下来转发（包括 /api/notes/、/api/health/）。
      '/api': {
        // ---- target：转发到哪 ----
        // Django 开发服务器默认在 8000。
        // ★ practice 那个项目的后端是 8001，两个项目同时跑时别搞混。
        //
        // ★★★ 为什么写 127.0.0.1 而不是 localhost？★★★
        //   Node 18+ 在解析 localhost 时可能优先走 IPv6（::1），
        //   而 Django 的 runserver 默认只监听 IPv4 的 127.0.0.1。
        //   结果就是代理报错：
        //     Error: connect ECONNREFUSED ::1:8000
        //   写死 127.0.0.1 可以稳定避开这个坑（这是很常见的踩坑点）。
        target: 'http://127.0.0.1:8000',

        // ---- changeOrigin：改写请求头里的 Host ----
        // 置为 true 后，转发时会把 Host 头改成 target 的域名（127.0.0.1:8000），
        // 而不是保留浏览器的 localhost:5173。
        //
        // ★ 为什么要改？
        //   有些后端（尤其是配置了 ALLOWED_HOSTS 的 Django）会校验 Host 头，
        //   发现是 localhost:5173 就直接返回 400 Bad Request。
        //   ★ 记住：这个选项几乎总是要写 true，忘了写就会出现
        //     「浏览器 400，但后端日志里连请求都没进来」的怪现象。
        changeOrigin: true

        // -------------------------------------------------------------------
        // ★★★ 这里【故意没有写 rewrite】★★★
        // -------------------------------------------------------------------
        // 很多教程会写：
        //     rewrite: (path) => path.replace(/^\/api/, '')
        // 意思是「把 /api 前缀剥掉再转发」——那是给「后端接口没有 /api 前缀」
        // 的项目用的。
        //
        // 但本项目 Django 的路由就是 /api/notes/（见 config/urls.py），
        // 所以必须【原样转发】：
        //     浏览器  /api/notes/   ->   Django  /api/notes/     ✅
        //
        // 如果照抄教程加了 rewrite，就会变成：
        //     浏览器  /api/notes/   ->   Django  /notes/         ❌ 404
        //
        // 这是新手照抄配置最常见的翻车点之一，所以特意在这里标注。
        // -------------------------------------------------------------------
      }
    }
  }

  // ★ 其他常用配置（本项目用不到，列出来方便以后查阅）：
  //
  //   base: '/app/',           // 部署到子目录时用，配合 Nginx 的 location
  //   build: {
  //     outDir: 'dist',        // 打包输出目录（默认就是 dist）
  //     sourcemap: false,      // 生产环境建议关掉，避免源码泄露
  //   },
  //   resolve: {
  //     alias: { '@': '/src' } // 之后就能写 import x from '@/api'
  //   }
})
